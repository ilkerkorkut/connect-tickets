CREATE TABLE repositories (
    id uuid PRIMARY KEY,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    owner varchar(255) NOT NULL,
    name varchar(255) NOT NULL,
    full_name varchar(512) NOT NULL,
    normalized_full_name varchar(512) NOT NULL UNIQUE,
    description varchar(4096),
    stars integer NOT NULL DEFAULT 0 CHECK (stars >= 0),
    language varchar(128),
    html_url varchar(2048) NOT NULL,
    notes varchar(4000) NOT NULL DEFAULT '',
    fetched_at timestamptz NOT NULL
);

CREATE INDEX repository_language ON repositories (language);
CREATE INDEX repository_stars ON repositories (stars);
CREATE INDEX repository_updated_at ON repositories (updated_at);
CREATE INDEX repository_fetched_at ON repositories (fetched_at);

CREATE TABLE batches (
    id uuid PRIMARY KEY,
    created_at timestamptz NOT NULL,
    completed_at timestamptz
);

CREATE TABLE batch_jobs (
    id uuid PRIMARY KEY,
    batch_id uuid NOT NULL REFERENCES batches (id) ON DELETE CASCADE,
    repo_id uuid NOT NULL REFERENCES repositories (id) ON DELETE RESTRICT,
    status varchar(32) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'queued', 'processing', 'retry_wait', 'succeeded', 'failed')),
    attempt_count integer NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    processing_owner varchar(128),
    lease_until timestamptz,
    next_attempt_at timestamptz,
    last_error_code varchar(64),
    last_error_message varchar(512),
    created_at timestamptz NOT NULL,
    started_at timestamptz,
    completed_at timestamptz,
    updated_at timestamptz NOT NULL,
    UNIQUE (batch_id, repo_id)
);

CREATE INDEX batchjob_batch_id_status ON batch_jobs (batch_id, status);
CREATE INDEX batchjob_status_next_attempt_at ON batch_jobs (status, next_attempt_at);
CREATE INDEX batchjob_status_lease_until ON batch_jobs (status, lease_until);
CREATE INDEX batchjob_repo_id_status ON batch_jobs (repo_id, status);

CREATE TABLE job_attempts (
    id uuid PRIMARY KEY,
    batch_job_id uuid NOT NULL REFERENCES batch_jobs (id) ON DELETE CASCADE,
    attempt_number integer NOT NULL CHECK (attempt_number > 0),
    worker_id varchar(128) NOT NULL,
    started_at timestamptz NOT NULL,
    finished_at timestamptz,
    result varchar(32) NOT NULL CHECK (result IN ('succeeded', 'failed', 'retry_scheduled')),
    error_code varchar(64),
    duration_ms integer NOT NULL DEFAULT 0 CHECK (duration_ms >= 0),
    UNIQUE (batch_job_id, attempt_number)
);

CREATE TABLE outbox_events (
    id uuid PRIMARY KEY,
    event_id varchar(128) NOT NULL UNIQUE,
    event_type varchar(64) NOT NULL,
    aggregate_id uuid NOT NULL,
    partition_key varchar(128) NOT NULL,
    payload jsonb NOT NULL,
    status varchar(32) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'publishing', 'published')),
    available_at timestamptz NOT NULL,
    publishing_owner varchar(128),
    publishing_lease_until timestamptz,
    publish_attempts integer NOT NULL DEFAULT 0 CHECK (publish_attempts >= 0),
    last_error varchar(512),
    published_at timestamptz,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL
);

CREATE INDEX outboxevent_status_available_at ON outbox_events (status, available_at);
CREATE INDEX outboxevent_status_publishing_lease_until ON outbox_events (status, publishing_lease_until);

CREATE TABLE change_sequences (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(64) NOT NULL UNIQUE,
    last_value bigint NOT NULL DEFAULT 0 CHECK (last_value >= 0)
);

INSERT INTO change_sequences (name, last_value)
VALUES ('repository_changes', 0)
ON CONFLICT (name) DO NOTHING;

CREATE TABLE repository_changes (
    id uuid PRIMARY KEY,
    sequence bigint NOT NULL UNIQUE,
    event_id varchar(128) NOT NULL UNIQUE,
    repo_id uuid,
    operation varchar(32) NOT NULL CHECK (operation IN ('created', 'notes_updated', 'refreshed', 'deleted')),
    repository_snapshot jsonb,
    changed_at timestamptz NOT NULL
);

CREATE INDEX repositorychange_repo_id_changed_at ON repository_changes (repo_id, changed_at);
CREATE INDEX repositorychange_operation_changed_at ON repository_changes (operation, changed_at);
